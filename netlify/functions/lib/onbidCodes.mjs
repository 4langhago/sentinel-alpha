/**
 * PNU(필지고유번호 19자리)에서 시군구 법정동코드 5자리를 뽑는다.
 *
 * PNU = 법정동코드(10) + 대장구분(1) + 본번(4) + 부번(4).
 * 앞 5자리가 그대로 우리 sgg_code라서, 이름 매칭 없이 실거래 지역과 정확히 조인된다.
 * 이게 온비드↔법정동코드 매핑 문제의 사실상 정답이다.
 */
export function sggCodeFromPnu(pnu) {
  const s = String(pnu || '').replace(/\D/g, '')
  return s.length >= 10 ? s.slice(0, 5) : ''
}

/**
 * 온비드 용도 소분류명 → 우리 PropertyType.
 * 실거래와 나란히 놓고 비교하려면 종목 축이 같아야 한다.
 * 매핑이 불가능한 것(공장·창고·유원지 등)은 'ETC'로 두고 억지로 끼워넣지 않는다.
 */
export function toPropertyType(mclsName, sclsName) {
  const s = sclsName || ''
  if (s === '아파트') return 'APARTMENT'
  if (s === '오피스텔') return 'OFFICETEL'
  if (mclsName === '토지') return 'LAND'
  if (mclsName === '상가용및업무용건물') return 'COMMERCIAL'
  // 빌라·단독·다세대 등 나머지 주거용은 실거래에 대응 종목이 없다.
  return 'ETC'
}
