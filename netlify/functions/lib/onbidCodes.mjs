/**
 * 광주광역시의 자치구. "전남광주통합특별시"를 광주와 전남으로 가르는 기준이다.
 * 광주는 5개 자치구뿐이라 목록이 고정이고, 나머지 시·군은 전부 옛 전남이다.
 */
const GWANGJU_GU = new Set(['동구', '서구', '남구', '북구', '광산구'])

/**
 * 온비드 시도명 → 우리 시도 약칭.
 *
 * 2026년 개편으로 등장한 "전남광주통합특별시"는 광주광역시와 옛 전라남도를
 * 한 이름에 묶어서, 단순 치환하면 둘 중 하나가 통째로 사라진다. 실제로 전부
 * '광주'로 보내고 있었고 그 결과 **전남 검색이 0건**이 되고, 광주 결과에
 * 목포·여수·나주 같은 도시가 섞여 "광주 목포시"라는 없는 조합이 화면에 떴다.
 *
 * 시군구명으로 가른다 — 광주 자치구 5개면 광주, 그 밖의 시·군이면 전남이다.
 * (PNU가 있으면 그쪽이 더 정확하므로 호출자가 PNU를 우선 쓴다.)
 *
 * @param {string} sidoRaw 온비드 lctnSdnm
 * @param {string} sggRaw 온비드 lctnSggnm
 */
export function resolveSido(sidoRaw, sggRaw = '') {
  if (sidoRaw === '전남광주통합특별시') {
    return GWANGJU_GU.has(sggRaw) ? '광주' : '전남'
  }
  return SIDO_ALIASES[sidoRaw] || sidoRaw
}

