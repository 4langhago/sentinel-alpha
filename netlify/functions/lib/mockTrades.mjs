export const generateTrades = (today = new Date()) => {
  const items = []
  TEMPLATE.forEach((t, i) => {
    const [sido, sgg, code, umd, name, area, buildYear, amountManwon] = t
    // 최근 90일 안에 분산
    const d = new Date(today.getTime() - ((i * 37) % 90) * 86400000)
    const dealDate = d.toISOString().slice(0, 10)
    const price = amountManwon * 10_000
    items.push({
      id: `mock-${code}-${name}-${area}-${dealDate}`,
      name,
      sgg_code: code,
      sido,
      sgg,
      region_name: `${sido} ${sgg}`,
      umd,
      jibun: '',
      address: umd,
      property_type: 'APARTMENT',
      deal_type: 'TRADE',
      rent_type: null,
      area,
      floor: 3 + (i % 20),
      build_year: buildYear,
      deal_date: dealDate,
      price,
      monthly_rent: 0,
      price_per_pyeong: Math.round((price / area) * 3.305785),
    })
  })
  return items.sort((a, b) => b.deal_date.localeCompare(a.deal_date))
}
